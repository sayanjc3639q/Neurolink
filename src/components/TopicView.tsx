import React from 'react';
import { TopicHeading } from '../lib/types';
import { WikiLink } from './WikiLink';

interface TopicViewProps {
  contentJson: string;
  onLinkFollow?: (slug: string, label: string) => void;
}

export function TopicView({ contentJson, onLinkFollow }: TopicViewProps) {
  let doc: any = null;
  try {
    doc = JSON.parse(contentJson);
  } catch {
    doc = null;
  }

  if (!doc || !doc.content) {
    return <p className="text-pencil italic">No content available for this topic.</p>;
  }

  const renderNode = (node: any, idx: number): React.ReactNode => {
    if (!node) return null;

    // Custom wikiLink node
    if (node.type === 'wikiLink' && node.attrs) {
      return (
        <WikiLink
          key={idx}
          slug={node.attrs.slug}
          label={node.attrs.label || node.attrs.slug}
          onLinkFollow={onLinkFollow}
        />
      );
    }

    // Text with marks
    if (node.type === 'text') {
      let element: React.ReactNode = node.text;

      if (node.marks) {
        for (const mark of node.marks) {
          if (mark.type === 'bold') {
            element = <strong>{element}</strong>;
          } else if (mark.type === 'italic') {
            element = <em>{element}</em>;
          } else if (mark.type === 'highlight') {
            element = <mark className="highlight-marker">{element}</mark>;
          } else if (mark.type === 'code') {
            element = <code>{element}</code>;
          } else if (mark.type === 'link') {
            element = (
              <a
                href={mark.attrs?.href}
                target="_blank"
                rel="noopener noreferrer"
                className="text-biro underline underline-offset-2 hover:opacity-80"
              >
                {element}
              </a>
            );
          } else if (mark.type === 'wikiLink' && mark.attrs) {
            element = (
              <WikiLink
                slug={mark.attrs.slug}
                label={node.text || mark.attrs.label}
                onLinkFollow={onLinkFollow}
              />
            );
          }
        }
      }
      return <React.Fragment key={idx}>{element}</React.Fragment>;
    }

    // Blocks
    const children = node.content?.map((child: any, i: number) => renderNode(child, i));

    switch (node.type) {
      case 'paragraph':
        return <p key={idx}>{children}</p>;
      case 'heading': {
        const level = node.attrs?.level || 2;
        // ID generated by extractLinks or generated here
        const textContent = extractPlainText(node);
        const headingId = textContent
          .toLowerCase()
          .replace(/[^\w\s-]/g, '')
          .replace(/\s+/g, '-');

        if (level === 2) {
          return (
            <h2 key={idx} id={headingId}>
              {children}
            </h2>
          );
        }
        return (
          <h3 key={idx} id={headingId}>
            {children}
          </h3>
        );
      }
      case 'bulletList':
        return <ul key={idx}>{children}</ul>;
      case 'orderedList':
        return <ol key={idx}>{children}</ol>;
      case 'listItem':
        return <li key={idx}>{children}</li>;
      case 'blockquote':
        return <blockquote key={idx}>{children}</blockquote>;
      case 'codeBlock':
        return (
          <pre key={idx}>
            <code>{children}</code>
          </pre>
        );
      case 'horizontalRule':
        return <hr key={idx} className="my-8 border-rule" />;
      default:
        return <div key={idx}>{children}</div>;
    }
  };

  function extractPlainText(node: any): string {
    if (node.text) return node.text;
    if (!node.content) return '';
    return node.content.map(extractPlainText).join('');
  }

  return (
    <article className="prose-wiki">
      {doc.content.map((child: any, i: number) => renderNode(child, i))}
    </article>
  );
}
